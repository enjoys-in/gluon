package tests

import (
	"testing"
)

func TestCapability(t *testing.T) {
	runOneToOneTest(t, defaultServerOptions(t), func(c *testConnection, _ *testSession) {
		c.C("A001 Capability")
		c.S(`* CAPABILITY AUTH=PLAIN ID IDLE IMAP4rev1 LITERAL+ SASL-IR STARTTLS`)
		c.S("A001 OK CAPABILITY")

		c.C(`A002 login "user" "pass"`)
		c.S(`A002 OK [CAPABILITY ACL AUTH=PLAIN BINARY CHILDREN CREATE-SPECIAL-USE ENABLE ESEARCH ESORT ID IDLE IMAP4rev1 LIST-EXTENDED LIST-STATUS LITERAL+ METADATA MOVE MULTIAPPEND NAMESPACE OBJECTID PREVIEW QUOTA QUOTASET RIGHTS=texk SASL-IR SEARCHRES SORT SORT=DISPLAY SPECIAL-USE STARTTLS STATUS=SIZE THREAD=REFERENCES UIDBATCHES UIDONLY UIDPLUS UNAUTHENTICATE UNSELECT UTF8=ACCEPT WITHIN] Logged in`)

		c.C("A003 Capability")
		c.S(`* CAPABILITY ACL AUTH=PLAIN BINARY CHILDREN CREATE-SPECIAL-USE ENABLE ESEARCH ESORT ID IDLE IMAP4rev1 LIST-EXTENDED LIST-STATUS LITERAL+ METADATA MOVE MULTIAPPEND NAMESPACE OBJECTID PREVIEW QUOTA QUOTASET RIGHTS=texk SASL-IR SEARCHRES SORT SORT=DISPLAY SPECIAL-USE STARTTLS STATUS=SIZE THREAD=REFERENCES UIDBATCHES UIDONLY UIDPLUS UNAUTHENTICATE UNSELECT UTF8=ACCEPT WITHIN`)
		c.S("A003 OK CAPABILITY")
	})
}

