package tests

import (
	"testing"
)

func TestCapability(t *testing.T) {
	runOneToOneTest(t, defaultServerOptions(t), func(c *testConnection, _ *testSession) {
		c.C("A001 Capability")
		c.S(`* CAPABILITY AUTH=PLAIN ID IDLE IMAP4rev1 LITERAL+ SASL-IR STARTTLS`)
		c.S("A001 OK CAPABILITY")

		c.C(`A002 login "user" "pass"`)
		c.S(`A002 OK [CAPABILITY AUTH=PLAIN CHILDREN CREATE-SPECIAL-USE ESEARCH ESORT ID IDLE IMAP4rev1 LIST-EXTENDED LIST-STATUS LITERAL+ MOVE MULTIAPPEND NAMESPACE QUOTA SASL-IR SEARCHRES SORT SORT=DISPLAY SPECIAL-USE STARTTLS STATUS=SIZE THREAD=REFERENCES UIDPLUS UNAUTHENTICATE UNSELECT WITHIN] Logged in`)

		c.C("A003 Capability")
		c.S(`* CAPABILITY AUTH=PLAIN CHILDREN CREATE-SPECIAL-USE ESEARCH ESORT ID IDLE IMAP4rev1 LIST-EXTENDED LIST-STATUS LITERAL+ MOVE MULTIAPPEND NAMESPACE QUOTA SASL-IR SEARCHRES SORT SORT=DISPLAY SPECIAL-USE STARTTLS STATUS=SIZE THREAD=REFERENCES UIDPLUS UNAUTHENTICATE UNSELECT WITHIN`)
		c.S("A003 OK CAPABILITY")
	})
}

