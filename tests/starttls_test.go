package tests

import "testing"

func TestStartTLS(t *testing.T) {
	runOneToOneTest(t, defaultServerOptions(t), func(c *testConnection, s *testSession) {
		c.C("A001 starttls")
		c.S("A001 OK Begin TLS negotiation now")

		c.upgradeConnection()

		c.C("A002 noop")
		c.OK("A002")

		c.C("A003 capability")
		c.S(`* CAPABILITY AUTH=PLAIN ID IDLE IMAP4rev1 LITERAL+ SASL-IR`)
		c.OK("A003")

		c.C("A004 starttls")
		c.S("A004 NO TLS is already active")

		c.C("A005 login user pass")
		c.S(`A005 OK [CAPABILITY AUTH=PLAIN CHILDREN CREATE-SPECIAL-USE ESEARCH ESORT ID IDLE IMAP4rev1 LIST-EXTENDED LIST-STATUS LITERAL+ MOVE MULTIAPPEND NAMESPACE QUOTA SASL-IR SEARCHRES SORT SORT=DISPLAY SPECIAL-USE STATUS=SIZE THREAD=REFERENCES UIDPLUS UNAUTHENTICATE UNSELECT WITHIN] Logged in`)

		c.C("A006 capability")
		c.S(`* CAPABILITY AUTH=PLAIN CHILDREN CREATE-SPECIAL-USE ESEARCH ESORT ID IDLE IMAP4rev1 LIST-EXTENDED LIST-STATUS LITERAL+ MOVE MULTIAPPEND NAMESPACE QUOTA SASL-IR SEARCHRES SORT SORT=DISPLAY SPECIAL-USE STATUS=SIZE THREAD=REFERENCES UIDPLUS UNAUTHENTICATE UNSELECT WITHIN`)
		c.OK("A006")
	})
}
